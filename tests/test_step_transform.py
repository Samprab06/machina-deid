import hashlib

import pytest
from step_helpers import DATA, step_bytes

from machina_deid import step_transform as st
from machina_deid.idmap import IdentityMap

NAME, ORG = "Jane Quincy Doe", "Acme Widgets Inc"


def imap(**kw):
    return IdentityMap(strings=kw.get("strings", {NAME: "Person A", ORG: "Org B"}))


def write(tmp_path, data, name="in.step"):
    p = tmp_path / name
    p.write_bytes(data)
    return p


def data_of(b: bytes) -> bytes:
    return b[b.index(b"\nDATA;") + 1:]


def test_replaces_header_fields_and_preserves_data(tmp_path):
    src_b = step_bytes()
    src = write(tmp_path, src_b)
    dst = tmp_path / "out.step"
    res = st.transform_step(src, dst, imap())
    assert res.outcome == "transformed_validated" and res.ok and res.output_written
    out = dst.read_bytes()
    assert data_of(out) == data_of(src_b) == DATA  # DATA byte-identical, incl. the name inside DATA
    assert b"Jane Quincy Doe point" in out  # DATA text is never touched
    head = out[:out.index(b"\nDATA;")]
    assert b"Person A bracket" in head and b"Person A" in head and b"Org B" in head
    assert NAME.encode() not in head and ORG.encode() not in head
    assert res.header_fields_changed == {"name": 1, "author": 1, "organization": 1}
    assert res.replacements == {0: 2, 1: 1}
    assert res.data_section_identical and res.data_bytes == len(DATA)
    assert res.source_sha256 == hashlib.sha256(src_b).hexdigest()
    assert res.output_sha256 == hashlib.sha256(out).hexdigest()
    assert res.input_bytes == len(src_b) and res.output_bytes == len(out)
    # untouched header parts: timestamp, preprocessor, schema, description
    assert b"2024-08-11T09:14:45-03:00" in out and b"ST-DEVELOPER v16.7" in out
    assert b"AUTOMOTIVE_DESIGN {1 0 10303 214 3 1 1}" in out and b"/* Generated by software */" in out
    # result never carries raw values
    assert NAME not in repr(res.to_dict()) and ORG not in repr(res.to_dict())
    assert not list(tmp_path.glob(".*.partial"))
    assert st.parse_step_bytes(out)  # reparses


def test_crlf_preserved(tmp_path):
    src_b = step_bytes(nl=b"\r\n")
    src = write(tmp_path, src_b)
    res = st.transform_step(src, tmp_path / "o.stp", imap())
    assert res.ok and res.newline_style == "crlf"
    out = (tmp_path / "o.stp").read_bytes()
    assert out.count(b"\r\n") == out.count(b"\n") == src_b.count(b"\n")


def test_system_fields_only_when_mapped_and_timestamp_not_by_default(tmp_path):
    src = write(tmp_path, step_bytes())
    m = IdentityMap(strings={"Solid Edge": "CAD-X", "2024-08-11T09:14:45-03:00": "T"})
    dst = tmp_path / "o.step"
    res = st.transform_step(src, dst, m)
    assert res.outcome == "transformed_validated"
    out = dst.read_bytes()
    assert b"'CAD-X'" in out and b"2024-08-11T09:14:45-03:00" in out  # timestamp unmapped by default
    assert res.mapped_present_in_unrequested_fields == {"timestamp": 1}
    dst2 = tmp_path / "o2.step"
    res2 = st.transform_step(src, dst2, m, fields=("timestamp",))
    assert b"'T'" in dst2.read_bytes() and b"Solid Edge" in dst2.read_bytes() and res2.ok


def test_no_match_is_inspected_no_identifiers_and_writes_nothing(tmp_path):
    src = write(tmp_path, step_bytes())
    dst = tmp_path / "o.step"
    res = st.transform_step(src, dst, IdentityMap(strings={"Nobody Here": "X"}))
    assert res.outcome == "inspected_no_identifiers" and res.ok and not res.output_written
    assert not dst.exists() and res.source_sha256 and res.output_sha256 == ""


def test_name_only_in_data_is_not_a_header_match(tmp_path):
    src = write(tmp_path, step_bytes(name="part", author="('Unknown')", org="('Unknown')"))
    res = st.transform_step(src, tmp_path / "o.step", IdentityMap(strings={"Jane Quincy Doe": "P"}))
    assert res.outcome == "inspected_no_identifiers"
    assert st.residual_counts(src, IdentityMap(strings={"Jane Quincy Doe": "P"})) == {0: 1}


def test_unmodifiable_when_escape_directive_or_bad_replacement(tmp_path):
    esc = write(tmp_path, step_bytes(name=r"Jane Quincy Doe \X2\00E9\X0"), "e.step")
    dst = tmp_path / "o.step"
    res = st.transform_step(esc, dst, imap())
    assert res.outcome == "identifiers_unmodifiable" and not dst.exists() and not res.ok
    plain = write(tmp_path, step_bytes(), "p.step")
    res = st.transform_step(plain, dst, IdentityMap(strings={NAME: "Zoë"}))  # non-ASCII replacement
    assert res.outcome == "identifiers_unmodifiable" and not dst.exists()
    res = st.transform_step(plain, dst, IdentityMap(strings={NAME: "bad\nvalue"}))
    assert res.outcome == "identifiers_unmodifiable" and not dst.exists()


def test_quote_and_backslash_escaping(tmp_path):
    src = write(tmp_path, step_bytes(name="O''Brien\\\\X part"))  # logical: O'Brien\X part
    dst = tmp_path / "o.step"
    res = st.transform_step(src, dst, IdentityMap(strings={"O'Brien": "It's \\ ok"}))
    assert res.ok
    hdr, _ = st.read_step_header(dst)
    s = next(x for x in hdr.strings if x.field == "name")
    assert hdr.text[s.start:s.end] == "'It''s \\\\ ok\\\\X part'"


def test_longest_match_and_no_chained_replacement(tmp_path):
    src = write(tmp_path, step_bytes(name="Acme Widgets Inc", org="('Acme')"))
    dst = tmp_path / "o.step"
    res = st.transform_step(src, dst, IdentityMap(strings={"Acme": "Widgets Inc", "Acme Widgets Inc": "Z"}))
    assert res.ok
    out = dst.read_bytes()
    assert b"/* name */ 'Z'" in out and b"('Widgets Inc')" in out


@pytest.mark.parametrize("mutate", [
    lambda b: b.replace(b"ISO-10303-21;", b"NOT-STEP;", 1),
    lambda b: b.replace(b"ENDSEC;\n\nDATA;", b"ENDSEC;\n\n", 1),
    lambda b: b.replace(b"END-ISO-10303-21;", b""),
    lambda b: b.replace(b"FILE_SCHEMA (('AUTOMOTIVE_DESIGN {1 0 10303 214 3 1 1}'));", b""),
    lambda b: b.replace(b"/* organization */ ('Acme Widgets Inc'),", b""),  # wrong arity
    lambda b: b.replace(b"'Jane Quincy Doe bracket'", b"'Jane Quincy Doe bracket"),  # unterminated string
    lambda b: b.replace(b"/* Generated", b"/* Generated unterminated", 1).replace(b"*/", b"", 1),
    lambda b: b[:60],
    lambda b: b"",
])
def test_malformed_is_failed_validation_and_writes_nothing(tmp_path, mutate):
    src = write(tmp_path, mutate(step_bytes()))
    dst = tmp_path / "o.step"
    res = st.transform_step(src, dst, imap())
    assert res.outcome == "failed_validation" and not res.ok and not dst.exists()
    assert res.reason and NAME not in res.reason
    assert not list(tmp_path.glob(".*.partial"))


def test_refuses_same_path_and_existing_output(tmp_path):
    src = write(tmp_path, step_bytes())
    with pytest.raises(ValueError):
        st.transform_step(src, src, imap())
    dst = tmp_path / "x.step"
    dst.write_bytes(b"keep")
    with pytest.raises(FileExistsError):
        st.transform_step(src, dst, imap())
    assert dst.read_bytes() == b"keep"


def test_verification_failure_leaves_no_output(tmp_path, monkeypatch):
    src = write(tmp_path, step_bytes())
    dst = tmp_path / "o.step"
    monkeypatch.setattr(st, "_hash_range", lambda p, start: ("0" * 64, 1))
    res = st.transform_step(src, dst, imap())
    assert res.outcome == "failed_validation" and res.reason == "data_section_changed" and not dst.exists()
    assert not list(tmp_path.glob(".*.partial"))


def test_cp1252_and_utf8_raw_names(tmp_path):
    raw = "José García".encode("utf-8").decode("latin-1")
    src = write(tmp_path, step_bytes(name="x " + raw))
    dst = tmp_path / "o.step"
    res = st.transform_step(src, dst, IdentityMap(strings={"José García": "Person C"}))
    assert res.ok and b"x Person C" in dst.read_bytes()


def test_inspect_is_read_only_and_matches_transform(tmp_path):
    src = write(tmp_path, step_bytes())
    r = st.inspect_step(src, imap())
    assert r.header_fields_changed == {"name": 1, "author": 1, "organization": 1}
    assert r.outcome == "transformed_validated" and r.reason == "plan_only"
    assert list(tmp_path.iterdir()) == [src]
